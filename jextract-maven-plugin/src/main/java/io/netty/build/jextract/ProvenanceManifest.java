package io.netty.build.jextract;

import org.jetbrains.annotations.Nullable;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;

/**
 * Records the toolchain that produced a set of generated bindings, written as a
 * {@code GENERATED.properties} file beside them so a reviewer (or a bisecting developer) can see
 * exactly which ABI snapshot the committed sources came from.
 *
 * <p>The rendered content is deliberately <strong>deterministic</strong>, no timestamps, absolute
 * paths, user or host names, so regenerating on the same pinned toolchain reproduces it byte-for-byte
 * and the reproducibility diff gate stays meaningful. A change in any recorded field (a jextract bump,
 * a different OS, a new SDK) surfaces as a reviewable diff rather than silent drift.
 */
final class ProvenanceManifest {

    static final String FILE_NAME = "GENERATED.properties";

    private final String jextractVersion;
    private final String os;
    @Nullable
    private final String sdk;

    ProvenanceManifest(final String jextractVersion, final String os, @Nullable final String sdk) {
        this.jextractVersion = jextractVersion;
        this.os = os;
        this.sdk = sdk;
    }

    /** A manifest for the OS this build runs on (jextract can only generate for the host OS). */
    static ProvenanceManifest forCurrentOs(final String jextractVersion, @Nullable final String sdk) {
        return new ProvenanceManifest(jextractVersion, normalizeOs(System.getProperty("os.name")), sdk);
    }

    /** Writes {@link #FILE_NAME} into {@code packageDirectory}, overwriting any previous manifest. */
    void writeInto(final File packageDirectory) throws JextractException {
        final Path file = packageDirectory.toPath().resolve(FILE_NAME);
        try {
            Files.write(file, render().getBytes(StandardCharsets.UTF_8));
        } catch (final IOException e) {
            throw JextractExceptions.executionError("Could not write provenance manifest " + file, e);
        }
    }

    /**
     * The manifest body. Uses a fixed key order and hard-coded {@code '\n'} line endings (never the
     * platform separator) so the output is identical on every machine.
     */
    String render() {
        final StringBuilder body = new StringBuilder()
                .append("# Generated by netty5-jextract-maven-plugin. Do not edit.\n")
                .append("# Records the toolchain that produced the sibling bindings.\n")
                .append("jextract.version=").append(jextractVersion).append('\n')
                .append("os=").append(os).append('\n');
        if (!StringUtils.isBlank(sdk)) {
            body.append("sdk=").append(sdk.trim()).append('\n');
        }
        return body.toString();
    }

    static String normalizeOs(@Nullable final String osName) {
        if (osName == null) {
            return "unknown";
        }
        final String lower = osName.toLowerCase(Locale.ROOT);
        if (lower.contains("mac") || lower.contains("darwin")) {
            return "macos";
        }
        if (lower.contains("linux")) {
            return "linux";
        }
        if (lower.contains("win")) {
            return "windows";
        }
        if (lower.contains("bsd")) {
            return "bsd";
        }
        return lower.split("\\s+")[0];
    }
}
